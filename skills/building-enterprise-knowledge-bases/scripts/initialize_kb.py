def write_if_missing(path: Path, content: str, *, bom: bool = False) -> bool:
    if path.exists():
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    encoding = "utf-8-sig" if bom else "utf-8"
    path.write_text(content, encoding=encoding)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description="初始化企业知识库 V2.0 标准结构")
    parser.add_argument("root", help="企业知识库根目录")
    parser.add_argument(
        "--profile",
        choices=["generic", "construction-bidding"],
        default="generic",
        help="行业档案；施工/工程/招投标企业使用 construction-bidding",
    )
    args = parser.parse_args()

    root = Path(args.root).expanduser().resolve()
    root.mkdir(parents=True, exist_ok=True)

    created_dirs = 0
    for rel in DIRS:
        p = root / rel
        if not p.exists():
            p.mkdir(parents=True, exist_ok=True)
            created_dirs += 1

    created_files = 0
    csv_files = dict(CSV_FILES)
    text_files = dict(TEXT_FILES)
    if args.profile == "construction-bidding":
        csv_files.update(CONSTRUCTION_BIDDING_CSV_FILES)
        text_files.update(CONSTRUCTION_BIDDING_TEXT_FILES)

    for rel, content in csv_files.items():
        created_files += int(write_if_missing(root / rel, content, bom=True))
    for rel, content in text_files.items():
        created_files += int(write_if_missing(root / rel, content))

    print(f"初始化完成：{root}")
    print(f"知识库版本：V2.0")
    print(f"档案类型：{args.profile}")
    print(f"新建目录：{created_dirs}")
    print(f"新建基础文件：{created_files}")
    print("已有目录和文件均未覆盖。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
